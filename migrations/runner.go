package migrations

import (
	"context"
	"fmt"
	"io"
	"sync"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/yoav/djan-go/db"
)

const advisoryLockKey = 7_316_204_801

const createHistoryTable = `CREATE TABLE IF NOT EXISTS djan_migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL,
    name text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source, name)
)`

var (
	postMigrateLock  sync.Mutex
	postMigrateHooks []func(ctx context.Context) error
)

// OnPostMigrate registers a hook run after every successful migrate (e.g. creating permissions).
func OnPostMigrate(hook func(ctx context.Context) error) {
	postMigrateLock.Lock()
	defer postMigrateLock.Unlock()
	postMigrateHooks = append(postMigrateHooks, hook)
}

// Status describes whether a migration was applied.
type Status struct {
	Source    string
	Name      string
	Applied   bool
	AppliedAt time.Time
}

func appliedMigrations(ctx context.Context, executor db.Executor) (map[string]time.Time, error) {
	if _, err := executor.Exec(ctx, createHistoryTable); err != nil {
		return nil, err
	}
	rows, err := executor.Query(ctx, "SELECT source, name, applied_at FROM djan_migrations")
	if err != nil {
		return nil, err
	}
	applied := map[string]time.Time{}
	var source, name string
	var appliedAt time.Time
	_, err = pgx.ForEachRow(rows, []any{&source, &name, &appliedAt}, func() error {
		applied[source+"/"+name] = appliedAt
		return nil
	})
	return applied, err
}

// ShowStatus lists every migration and whether it was applied.
func ShowStatus(ctx context.Context, pool *pgxpool.Pool, sources []Source) ([]Status, error) {
	applied, err := appliedMigrations(ctx, pool)
	if err != nil {
		return nil, err
	}
	var statuses []Status
	for _, source := range sources {
		migrations, err := Load(source)
		if err != nil {
			return nil, err
		}
		for _, migration := range migrations {
			appliedAt, ok := applied[source.Name+"/"+migration.Name]
			statuses = append(statuses, Status{Source: source.Name, Name: migration.Name, Applied: ok, AppliedAt: appliedAt})
		}
	}
	return statuses, nil
}

// Pending counts unapplied migrations.
func Pending(ctx context.Context, pool *pgxpool.Pool, sources []Source) (int, error) {
	statuses, err := ShowStatus(ctx, pool, sources)
	count := 0
	for _, status := range statuses {
		if !status.Applied {
			count++
		}
	}
	return count, err
}

func withLock(ctx context.Context, pool *pgxpool.Pool, fn func(connection *pgxpool.Conn) error) error {
	connection, err := pool.Acquire(ctx)
	if err != nil {
		return err
	}
	defer connection.Release()
	if _, err := connection.Exec(ctx, "SELECT pg_advisory_lock($1)", int64(advisoryLockKey)); err != nil {
		return err
	}
	defer connection.Exec(context.WithoutCancel(ctx), "SELECT pg_advisory_unlock($1)", int64(advisoryLockKey))
	return fn(connection)
}

// Migrate applies pending migrations of every source in order, each in its own transaction,
// then runs post-migrate hooks. It returns the number of applied migrations.
func Migrate(ctx context.Context, pool *pgxpool.Pool, sources []Source, log io.Writer) (int, error) {
	if log == nil {
		log = io.Discard
	}
	count := 0
	err := withLock(ctx, pool, func(connection *pgxpool.Conn) error {
		applied, err := appliedMigrations(ctx, connection)
		if err != nil {
			return err
		}
		for _, source := range sources {
			migrations, err := Load(source)
			if err != nil {
				return err
			}
			for _, migration := range migrations {
				if _, done := applied[source.Name+"/"+migration.Name]; done {
					continue
				}
				fmt.Fprintf(log, "  Applying %s.%s...", source.Name, migration.Name)
				err := pgx.BeginFunc(ctx, connection, func(transaction pgx.Tx) error {
					for _, statement := range migration.Up {
						if _, err := transaction.Exec(ctx, statement); err != nil {
							return fmt.Errorf("%w\n%s", err, statement)
						}
					}
					_, err := transaction.Exec(ctx, "INSERT INTO djan_migrations (source, name) VALUES ($1, $2)", source.Name, migration.Name)
					return err
				})
				if err != nil {
					fmt.Fprintln(log, " FAILED")
					return fmt.Errorf("migrations: %s.%s: %w", source.Name, migration.Name, err)
				}
				fmt.Fprintln(log, " OK")
				count++
			}
		}
		return nil
	})
	if err != nil {
		return count, err
	}
	postMigrateLock.Lock()
	hooks := append([]func(context.Context) error(nil), postMigrateHooks...)
	postMigrateLock.Unlock()
	hookContext := db.WithPool(ctx, pool)
	for _, hook := range hooks {
		if err := hook(hookContext); err != nil {
			return count, fmt.Errorf("migrations: post-migrate hook: %w", err)
		}
	}
	return count, nil
}

// Rollback unapplies the last steps applied migrations of one source using their down SQL.
func Rollback(ctx context.Context, pool *pgxpool.Pool, source Source, steps int, log io.Writer) (int, error) {
	if log == nil {
		log = io.Discard
	}
	count := 0
	err := withLock(ctx, pool, func(connection *pgxpool.Conn) error {
		applied, err := appliedMigrations(ctx, connection)
		if err != nil {
			return err
		}
		migrations, err := Load(source)
		if err != nil {
			return err
		}
		for index := len(migrations) - 1; index >= 0 && count < steps; index-- {
			migration := migrations[index]
			if _, done := applied[source.Name+"/"+migration.Name]; !done {
				continue
			}
			fmt.Fprintf(log, "  Unapplying %s.%s...", source.Name, migration.Name)
			err := pgx.BeginFunc(ctx, connection, func(transaction pgx.Tx) error {
				for _, statement := range migration.Down {
					if _, err := transaction.Exec(ctx, statement); err != nil {
						return fmt.Errorf("%w\n%s", err, statement)
					}
				}
				_, err := transaction.Exec(ctx, "DELETE FROM djan_migrations WHERE source = $1 AND name = $2", source.Name, migration.Name)
				return err
			})
			if err != nil {
				fmt.Fprintln(log, " FAILED")
				return err
			}
			fmt.Fprintln(log, " OK")
			count++
		}
		return nil
	})
	return count, err
}
