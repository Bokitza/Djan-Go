package migrations

import (
	"context"
	"database/sql"
	"fmt"
	"io"
	"sync"
	"time"

	"github.com/Bokitza/djan-go/db"
)

func createHistoryTable(dialect db.Dialect) string {
	if dialect.Name() == "sqlite" {
		return `CREATE TABLE IF NOT EXISTS djan_migrations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    source TEXT NOT NULL,
    name TEXT NOT NULL,
    applied_at DATETIME NOT NULL DEFAULT (` + dialect.Now() + `),
    UNIQUE (source, name)
)`
	}
	return `CREATE TABLE IF NOT EXISTS djan_migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL,
    name text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source, name)
)`
}

var (
	postMigrateLock  sync.Mutex
	postMigrateHooks []func(ctx context.Context) error
)

// OnPostMigrate registers a hook run after every successful migrate (e.g. creating permissions).
func OnPostMigrate(hook func(ctx context.Context) error) {
	postMigrateLock.Lock()
	defer postMigrateLock.Unlock()
	postMigrateHooks = append(postMigrateHooks, hook)
}

// Status describes whether a migration was applied.
type Status struct {
	Source    string
	Name      string
	Applied   bool
	AppliedAt time.Time
}

func appliedMigrations(ctx context.Context, executor db.Executor, dialect db.Dialect) (map[string]time.Time, error) {
	if _, err := executor.ExecContext(ctx, createHistoryTable(dialect)); err != nil {
		return nil, err
	}
	rows, err := executor.QueryContext(ctx, "SELECT source, name, applied_at FROM djan_migrations")
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	applied := map[string]time.Time{}
	for rows.Next() {
		var source, name string
		var appliedAt time.Time
		if err := rows.Scan(&source, &name, &appliedAt); err != nil {
			return nil, err
		}
		applied[source+"/"+name] = appliedAt
	}
	return applied, rows.Err()
}

// ShowStatus lists every migration and whether it was applied.
func ShowStatus(ctx context.Context, adapter db.Adapter, sources []Source) ([]Status, error) {
	applied, err := appliedMigrations(ctx, adapter.Database(), adapter.Dialect())
	if err != nil {
		return nil, err
	}
	var statuses []Status
	for _, source := range sources {
		migrations, err := Load(source)
		if err != nil {
			return nil, err
		}
		for _, migration := range migrations {
			appliedAt, ok := applied[source.Name+"/"+migration.Name]
			statuses = append(statuses, Status{Source: source.Name, Name: migration.Name, Applied: ok, AppliedAt: appliedAt})
		}
	}
	return statuses, nil
}

// Pending counts unapplied migrations.
func Pending(ctx context.Context, adapter db.Adapter, sources []Source) (int, error) {
	statuses, err := ShowStatus(ctx, adapter, sources)
	count := 0
	for _, status := range statuses {
		if !status.Applied {
			count++
		}
	}
	return count, err
}

func withLock(ctx context.Context, adapter db.Adapter, fn func(connection *sql.Conn) error) error {
	connection, err := adapter.Database().Conn(ctx)
	if err != nil {
		return err
	}
	defer connection.Close()
	unlock, err := adapter.Dialect().LockMigrations(ctx, connection)
	if err != nil {
		return err
	}
	defer unlock()
	return fn(connection)
}

// SQL returns the statements that apply (up) or unapply the migration on the dialect. Postgres runs
// the SQL stored in the file; other dialects render it from the operations, starting from before,
// the state of the migration's source before it.
func (m *Migration) SQL(dialect db.Dialect, before *State, up bool) ([]string, error) {
	switch {
	case dialect.Name() != "sqlite" && up:
		return m.Up, nil
	case dialect.Name() != "sqlite":
		return m.Down, nil
	case up:
		return sqliteUp(m.Operations, before)
	}
	return sqliteDown(m.Operations, before)
}

// runMigration runs statements in a transaction and records (up) or removes the history row.
// It returns false without changes when another process already did so.
func runMigration(ctx context.Context, connection *sql.Conn, dialect db.Dialect, source, name string, statements []string, up bool) (bool, error) {
	sqlite := dialect.Name() == "sqlite"
	if sqlite {
		if _, err := connection.ExecContext(ctx, "PRAGMA foreign_keys = OFF"); err != nil {
			return false, err
		}
		defer connection.ExecContext(context.WithoutCancel(ctx), "PRAGMA foreign_keys = ON")
	}
	transaction, err := connection.BeginTx(ctx, nil)
	if err != nil {
		return false, err
	}
	defer transaction.Rollback()
	var recorded int
	err = transaction.QueryRowContext(ctx, fmt.Sprintf("SELECT count(*) FROM djan_migrations WHERE source = %s AND name = %s",
		dialect.Placeholder(1), dialect.Placeholder(2)), source, name).Scan(&recorded)
	if err != nil {
		return false, err
	}
	if (recorded > 0) == up {
		return false, nil
	}
	for _, statement := range statements {
		if _, err := transaction.ExecContext(ctx, statement); err != nil {
			return false, fmt.Errorf("%w\n%s", err, statement)
		}
	}
	history := "INSERT INTO djan_migrations (source, name) VALUES (%s, %s)"
	if !up {
		history = "DELETE FROM djan_migrations WHERE source = %s AND name = %s"
	}
	if _, err := transaction.ExecContext(ctx, fmt.Sprintf(history, dialect.Placeholder(1), dialect.Placeholder(2)), source, name); err != nil {
		return false, err
	}
	if sqlite {
		if err := checkForeignKeys(ctx, transaction); err != nil {
			return false, err
		}
	}
	return true, transaction.Commit()
}

func checkForeignKeys(ctx context.Context, transaction *sql.Tx) error {
	rows, err := transaction.QueryContext(ctx, "PRAGMA foreign_key_check")
	if err != nil {
		return err
	}
	defer rows.Close()
	if rows.Next() {
		var table, parent string
		var row, constraint sql.NullInt64
		if err := rows.Scan(&table, &row, &parent, &constraint); err != nil {
			return err
		}
		return fmt.Errorf("foreign key violation: a row of %s references a missing row of %s", table, parent)
	}
	return rows.Err()
}

// Migrate applies pending migrations of every source in order, each in its own transaction,
// then runs post-migrate hooks. It returns the number of applied migrations.
func Migrate(ctx context.Context, adapter db.Adapter, sources []Source, log io.Writer) (int, error) {
	if log == nil {
		log = io.Discard
	}
	dialect := adapter.Dialect()
	count := 0
	err := withLock(ctx, adapter, func(connection *sql.Conn) error {
		applied, err := appliedMigrations(ctx, connection, dialect)
		if err != nil {
			return err
		}
		for _, source := range sources {
			migrations, err := Load(source)
			if err != nil {
				return err
			}
			state := NewState()
			for _, migration := range migrations {
				before := state.clone()
				if err := replayInto(state, migration); err != nil {
					return err
				}
				if _, done := applied[source.Name+"/"+migration.Name]; done {
					continue
				}
				fmt.Fprintf(log, "  Applying %s.%s...", source.Name, migration.Name)
				statements, err := migration.SQL(dialect, before, true)
				if err == nil {
					_, err = runMigration(ctx, connection, dialect, source.Name, migration.Name, statements, true)
				}
				if err != nil {
					fmt.Fprintln(log, " FAILED")
					return fmt.Errorf("migrations: %s.%s: %w", source.Name, migration.Name, err)
				}
				fmt.Fprintln(log, " OK")
				count++
			}
		}
		return nil
	})
	if err != nil {
		return count, err
	}
	postMigrateLock.Lock()
	hooks := append([]func(context.Context) error(nil), postMigrateHooks...)
	postMigrateLock.Unlock()
	hookContext := db.WithAdapter(ctx, adapter)
	for _, hook := range hooks {
		if err := hook(hookContext); err != nil {
			return count, fmt.Errorf("migrations: post-migrate hook: %w", err)
		}
	}
	return count, nil
}

func replayInto(state *State, migration *Migration) error {
	for _, operation := range migration.Operations {
		if err := operation.Apply(state); err != nil {
			return fmt.Errorf("%s: %w", migration.Name, err)
		}
	}
	return nil
}

// Rollback unapplies the last steps applied migrations of one source using their down SQL.
func Rollback(ctx context.Context, adapter db.Adapter, source Source, steps int, log io.Writer) (int, error) {
	if log == nil {
		log = io.Discard
	}
	dialect := adapter.Dialect()
	count := 0
	err := withLock(ctx, adapter, func(connection *sql.Conn) error {
		applied, err := appliedMigrations(ctx, connection, dialect)
		if err != nil {
			return err
		}
		migrations, err := Load(source)
		if err != nil {
			return err
		}
		befores := make([]*State, len(migrations))
		state := NewState()
		for index, migration := range migrations {
			befores[index] = state.clone()
			if err := replayInto(state, migration); err != nil {
				return err
			}
		}
		for index := len(migrations) - 1; index >= 0 && count < steps; index-- {
			migration := migrations[index]
			if _, done := applied[source.Name+"/"+migration.Name]; !done {
				continue
			}
			fmt.Fprintf(log, "  Unapplying %s.%s...", source.Name, migration.Name)
			statements, err := migration.SQL(dialect, befores[index], false)
			if err == nil {
				_, err = runMigration(ctx, connection, dialect, source.Name, migration.Name, statements, false)
			}
			if err != nil {
				fmt.Fprintln(log, " FAILED")
				return fmt.Errorf("migrations: %s.%s: %w", source.Name, migration.Name, err)
			}
			fmt.Fprintln(log, " OK")
			count++
		}
		return nil
	})
	return count, err
}
