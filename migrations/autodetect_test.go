package migrations

import (
	"strings"
	"testing"
)

func types(operations []Operation) string {
	names := make([]string, len(operations))
	for index, operation := range operations {
		names[index] = operation.Type
	}
	return strings.Join(names, ",")
}

func postTable() *Table {
	return &Table{
		Name: "blog_post",
		Columns: []*Column{
			{Name: "id", Type: "bigint", PrimaryKey: true},
			{Name: "title", Type: "varchar(200)"},
			{Name: "author_id", Type: "bigint", ForeignKey: &ForeignKey{Table: "blog_author", Column: "id", OnDelete: "CASCADE"}},
		},
		Indexes: []*Index{{Name: "blog_post_author_id_idx", Columns: []string{"author_id"}}},
	}
}

func authorTable() *Table {
	return &Table{Name: "blog_author", Columns: []*Column{{Name: "id", Type: "bigint", PrimaryKey: true}, {Name: "name", Type: "text"}}}
}

func TestDiffCreatesTablesThenIndexesThenForeignKeys(t *testing.T) {
	target := &State{Tables: map[string]*Table{"blog_post": postTable(), "blog_author": authorTable()}}
	operations := Diff(NewState(), target)
	if got := types(operations); got != "create_table,create_table,add_index,add_foreign_key" {
		t.Fatalf("operations: %s", got)
	}
	replayed := NewState()
	for _, operation := range operations {
		if err := operation.Apply(replayed); err != nil {
			t.Fatal(err)
		}
	}
	if remaining := Diff(replayed, target); len(remaining) != 0 {
		t.Fatalf("replaying the diff should reach the target, left: %s", types(remaining))
	}
	migration := NewMigration("0001_initial", operations)
	joined := strings.Join(migration.Up, ";\n")
	for _, want := range []string{
		`"id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
		`"title" varchar(200) NOT NULL`,
		`CREATE INDEX "blog_post_author_id_idx" ON "blog_post" ("author_id")`,
		`ADD CONSTRAINT "blog_post_author_id_fkey" FOREIGN KEY ("author_id") REFERENCES "blog_author" ("id") ON DELETE CASCADE`,
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("up SQL is missing %q:\n%s", want, joined)
		}
	}
	if migration.Down[0] != `ALTER TABLE "blog_post" DROP CONSTRAINT "blog_post_author_id_fkey"` {
		t.Errorf("down SQL should start by reversing the last operation: %v", migration.Down)
	}
}

func TestDiffAlterations(t *testing.T) {
	current := &State{Tables: map[string]*Table{"blog_post": postTable(), "blog_author": authorTable()}}
	target := &State{Tables: map[string]*Table{"blog_post": postTable()}}
	post := target.Tables["blog_post"]
	post.Columns[1] = &Column{Name: "title", Type: "text", Nullable: true}
	post.Columns = append(post.Columns, &Column{Name: "views", Type: "bigint", Default: "0"}, &Column{Name: "slug", Type: "varchar(50)"})
	post.Columns[2].ForeignKey = nil
	post.Indexes = []*Index{{Name: "blog_post_slug_key", Columns: []string{"slug"}, Unique: true}}

	operations := Diff(current, target)
	if got := types(operations); got != "drop_index,drop_foreign_key,drop_table,add_column,add_column,alter_column,add_index" {
		t.Fatalf("operations: %s", got)
	}
	migration := NewMigration("0002", operations)
	joined := strings.Join(migration.Up, ";\n")
	for _, want := range []string{
		`ALTER TABLE "blog_post" ALTER COLUMN "title" TYPE text USING "title"::text`,
		`ALTER TABLE "blog_post" ALTER COLUMN "title" DROP NOT NULL`,
		`ADD COLUMN "slug" varchar(50) NOT NULL DEFAULT ''`,
		`ALTER COLUMN "slug" DROP DEFAULT`,
		`ADD COLUMN "views" bigint NOT NULL DEFAULT 0`,
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("missing %q in:\n%s", want, joined)
		}
	}
}

func TestLongIdentifiersAreShortened(t *testing.T) {
	name := identifierName(strings.Repeat("a", 40), []string{strings.Repeat("b", 30)}, "idx")
	if len(name) > 63 || !strings.HasSuffix(name, "_idx") {
		t.Fatalf("bad identifier %q (%d)", name, len(name))
	}
}
